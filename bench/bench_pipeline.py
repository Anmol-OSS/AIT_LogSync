"""LogSync ULPF - pipeline benchmark: the numbers slide 4 said were not yet measured.

    python bench/bench_pipeline.py                 # N=3000 lines per family
    set BENCH_N=10000 && python bench/bench_pipeline.py

Measures on THIS machine, single core, and writes docs/BENCHMARKS.md:
  1. tokenize throughput: Python reference vs WASM sandbox (per call, batched)
  2. full worker chain: archive + fsync + Merkle + WASM parse + provenance
     + round-trip gate + SQLite index + Parquet lake
  3. verification latency per event (re-parse from archived bytes + Merkle proof)
  4. archive compression on the real sealed segments
  5. round-trip pass rate per source family, clean and with damaged lines
"""
import gzip
import os
import platform
import random
import statistics
import sys
import tempfile
import time
from datetime import datetime
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "backend"))

from logsync.config import Settings  # noqa: E402
from logsync.core.engine import PythonEngine  # noqa: E402
from logsync.core.pack import load_pack  # noqa: E402
from logsync.core.processor import Processor, RawEvent  # noqa: E402
from logsync.core.verify import verify_event  # noqa: E402
from logsync.core.wasm_host import WasmEngine  # noqa: E402
from logsync.generators import SOURCES, generate_lines  # noqa: E402

N = int(os.environ.get("BENCH_N", "3000"))
TS = "2026-09-25T09:00:00+05:30"


def rate(n, seconds):
    return n / seconds if seconds else float("inf")


def main() -> int:
    families = [n for n, s in SOURCES.items() if s.has_pack]
    packs = {p.source_name: p for p in (load_pack(f.read_text(encoding="utf-8"))
                                        for f in (REPO / "packs").glob("*.yaml"))}
    corpus = {n: [ln.encode() for ln in generate_lines(n, N, seed=2026)] for n in families}
    out = []
    say = lambda s="": (print(s), out.append(s))

    say("# LogSync ULPF - measured benchmarks")
    say()
    say("Generated by `bench/bench_pipeline.py` on %s. Python %s, %s, %s, single core. "
        "N = %d synthetic lines per family (%d total)." % (
            datetime.now().strftime("%Y-%m-%d"), platform.python_version(), platform.machine(),
            platform.processor() or platform.system(), N, N * len(families)))
    say()

    # 1. tokenize
    py, wasm = PythonEngine(), WasmEngine()
    say("## 1. Tokenize throughput (lines/s)")
    say()
    say("| family | Python reference | WASM, one call per line | WASM, batch of 512 |")
    say("|---|---:|---:|---:|")
    tot = {"py": 0.0, "w1": 0.0, "wb": 0.0}
    for n in families:
        spec, lines = packs[n].spec, corpus[n]
        t = time.perf_counter(); [py.tokenize(spec, ln) for ln in lines]; a = time.perf_counter() - t
        t = time.perf_counter(); [wasm.tokenize(spec, ln) for ln in lines[:1000]]; b = (time.perf_counter() - t) * len(lines) / 1000
        t = time.perf_counter()
        for i in range(0, len(lines), 512):
            wasm.tokenize_many(spec, lines[i:i + 512])
        c = time.perf_counter() - t
        tot["py"] += a; tot["w1"] += b; tot["wb"] += c
        say("| %s | %s | %s | %s |" % (n, f"{rate(len(lines), a):,.0f}", f"{rate(len(lines), b):,.0f}", f"{rate(len(lines), c):,.0f}"))
    total = N * len(families)
    say("| **all** | **%s** | **%s** | **%s** |" % (f"{rate(total, tot['py']):,.0f}", f"{rate(total, tot['w1']):,.0f}",
                                                   f"{rate(total, tot['wb']):,.0f}"))
    say()
    say("Sandbox overhead is per *crossing*, not per byte: batching removes it (slide 4, open question 1).")
    say()

    # 2. full chain
    tmp = Path(tempfile.mkdtemp())
    settings = Settings(data_dir=tmp / "data", packs_dir=REPO / "packs", parser_engine="wasm", tsa="openssl")
    proc = Processor(settings)
    mixed = [ln for group in zip(*corpus.values()) for ln in group]
    events = [RawEvent("b-%d" % i, TS, "10.0.0.%d" % (i % 250), ln) for i, ln in enumerate(mixed)]
    t = time.perf_counter()
    for i in range(0, len(events), 512):
        proc.process_batch(events[i:i + 512])
    proc.flush()
    chain = time.perf_counter() - t
    say("## 2. Full worker chain")
    say()
    say("Archive (write-first) → Merkle leaf (fsync per batch) → WASM tokenize → normalize with per-field "
        "provenance → round-trip gate → SQLite index → Parquet lake, plus signed tree heads with RFC 3161 "
        "timestamps every 2 s.")
    say()
    say("- **%s events/s per core** (%d events in %.2f s)" % (f"{rate(len(events), chain):,.0f}", len(events), chain))
    say("- Cores needed for the deck's 1 B events/day (11.6k EPS average): **%.1f**; for the 3× burst (34.7k EPS): **%.1f**"
        % (11_600 / rate(len(events), chain), 34_700 / rate(len(events), chain)))
    say("- Slide 4's 139,654 events/s covers only parse → serialize → SHA-256; the difference is the evidence "
        "work (archive, Merkle, provenance for ~20 fields per event, index, lake).")
    say()

    # 3. verification latency
    conn = proc.db.connect()
    import json
    docs = [json.loads(r["doc"]) for r in conn.execute("SELECT doc FROM events ORDER BY RANDOM() LIMIT 200")]
    lat = []
    for d in docs:
        t = time.perf_counter()
        r = verify_event(d, proc.evidence, proc.registry, proc.engine)
        lat.append((time.perf_counter() - t) * 1000)
        assert r["overall"] == "verified", r
    say("## 3. Verification latency (re-derive from archived bytes)")
    say()
    say("200 random events, all five checks: median **%.1f ms**, p95 **%.1f ms** per event. All 200 verified."
        % (statistics.median(lat), sorted(lat)[int(len(lat) * 0.95)]))
    say()

    # 4. compression
    proc.evidence.archive.seal_active()
    raw_bytes = sum(len(e.raw) for e in events)
    sealed = sum(p.stat().st_size for p in (settings.data_dir / "archive").glob("*.gz"))
    unique = conn.execute("SELECT SUM(length) s FROM objects").fetchone()["s"]
    say("## 4. Raw archive")
    say()
    say("- %s raw bytes received, %s unique after content addressing, **%s on disk** sealed with gzip-6 "
        "→ **%.1f× smaller** (synthetic logs repeat more than live traffic: treat as an upper bound)."
        % (f"{raw_bytes:,}", f"{unique:,}", f"{sealed:,}", raw_bytes / sealed if sealed else 0))
    say("- Average event: %.0f bytes." % (raw_bytes / len(events)))
    say()

    # 5. round-trip per family
    from logsync.core.event import build_event
    say("## 5. Round-trip gate per family")
    say()
    say("| family | clean lines accepted | trailing garbage blocked | truncated lines blocked |")
    say("|---|---:|---:|---:|")
    rng = random.Random(9)

    def blocked(n, lines):
        spec = packs[n].spec
        return sum(1 for i, (ln, tok) in enumerate(zip(lines, wasm.tokenize_many(spec, lines)))
                   if build_event(event_id=str(i), received_at=TS, source_host="h", raw=ln, sha256="0",
                                  archive_ref="r", leaf_index=i, pack=packs[n], tok=tok)["status"] != "accepted")

    for n in families:
        rows = conn.execute("SELECT status, COUNT(*) c FROM events WHERE source_name = ? GROUP BY status", (n,)).fetchall()
        acc = {r["status"]: r["c"] for r in rows}.get("accepted", 0)
        garbage = [ln + b" ~%02x~" % rng.randint(0, 255) for ln in corpus[n][:500]]
        truncated = [ln[:rng.randint(len(ln) // 3, len(ln) - 2)] for ln in corpus[n][:500]]
        say("| %s | %d / %d (%.1f%%) | %d / 500 | %d / 500 |" % (
            n, acc, N, 100 * acc / N, blocked(n, garbage), blocked(n, truncated)))
    say()
    say("What the gate guarantees: every byte is either grammar, inside a captured field, or the event is "
        "blocked - and every declared check and transform holds. What no parser can know from bytes alone: "
        "text appended to a *free-text* last field (a CEF `msg`, a LEEF rule name) is indistinguishable from "
        "a longer value, and a line cut exactly at a field boundary looks like a shorter valid record. Those "
        "events are accepted with the bytes they actually contain - nothing is invented or dropped - and the "
        "raw line stays archived and provable either way.")
    say()

    Path(REPO / "docs").mkdir(exist_ok=True)
    (REPO / "docs" / "BENCHMARKS.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print("\nwrote docs/BENCHMARKS.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
