"""Self-evolving parser: DETECT -> SYNTHESIZE -> VALIDATE -> PROMOTE.

    draft(sample)   Drain structure + offline LLM labels -> candidate pack,
                    validated against held-out dead-letter lines. Nothing is
                    deployed; the analyst sees the pattern, fields and gate.
    approve(req)    the analyst's field mapping is applied, the final pack must
                    pass the gate again, then it is signed, written to the
                    registry (hot-loaded, no restart) and the archived
                    dead-letter events of that format are re-parsed.

LLM proposes. Deterministic tests decide. Human approves.
"""
import hashlib
import json
import logging
import re
import time
import uuid
from collections import Counter
from datetime import datetime, timezone

import yaml

from ..api import models as m
from ..config import Settings
from ..core.engine import PythonEngine
from ..core.pack import PackError, load_pack
from ..core.processor import pack_signer
from ..core.registry import Registry
from ..storage.db import Database
from . import infer, validate
from .llm import UES_TARGETS, LLMUnavailable, OllamaClient

log = logging.getLogger("logsync.synth")
_CAPTURE = re.compile(r"%\{(\w+):(\w+)\}")
HEADER_FIELDS = {"pri": "(ignore)", "ts": "time", "host": "device.hostname"}


def _slug(s: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")[:40]


def _safe_name(name: str) -> str | None:
    n = re.sub(r"[^a-z0-9_]", "_", name.strip().lower())[:32].strip("_")
    return n if re.fullmatch(r"[a-z][a-z0-9_]*", n or "") else None


INT_TARGETS = {"connection_info.protocol_num", "traffic.bytes_in", "traffic.bytes_out", "severity_id"}
TIME_TYPES = {"SYSLOGTIMESTAMP", "CISCOTIMESTAMP", "TIMESTAMP_ISO8601", "INT"}


def compatible(target: str, grok_type: str) -> bool:
    """Does a UES target make sense for a value of this detected type?"""
    if target.endswith(".ip"):
        return grok_type in ("IP", "IPV4", "IPV6")
    if target.endswith(".port") or target in INT_TARGETS:
        return grok_type in ("INT", "POSINT", "NONNEGINT")
    if target == "time":
        return grok_type in TIME_TYPES
    return True


def name_fits(name: str, grok_type: str) -> bool:
    """Reject names that contradict the data, e.g. 'nat_src_ip' for an integer."""
    words = set(name.split("_"))
    if "ip" in words and grok_type not in ("IP", "IPV4", "IPV6"):
        return False
    if "port" in words and grok_type not in ("INT", "POSINT", "NONNEGINT"):
        return False
    return True


def transforms_for(target: str, grok_type: str) -> list:
    if target.endswith(".ip"):
        return ["ip"]
    if target.endswith(".port") or target in ("connection_info.protocol_num", "traffic.bytes_in",
                                              "traffic.bytes_out", "severity_id"):
        return ["int"]
    if target == "time":
        return {"SYSLOGTIMESTAMP": ["rfc3164", "tz"], "CISCOTIMESTAMP": ["rfc3164", "tz"],
                "TIMESTAMP_ISO8601": ["iso8601", "tz"], "INT": ["epoch_s", "tz"]}.get(grok_type, [])
    if target == "connection_info.protocol_name":
        return ["lower"]
    return []


def build_pack_text(cand: dict, mapping: dict[str, str], pack_id: str, version: str) -> str:
    types = {name: t for t, name in _CAPTURE.findall(cand["header"] + cand["pattern"])}
    field_map: dict = {}
    for name, target in mapping.items():
        if target in ("", "(ignore)") or name not in types or target in field_map:
            continue                       # unmapped captures stay in the event under unmapped.*
        steps = transforms_for(target, types[name])
        field_map[target] = {"from": name, "transforms": steps} if steps else name
    doc = {
        "id": pack_id, "version": version,
        "vendor": cand["vendor"] or "Unknown", "product": cand["product"] or "Unknown",
        "family": " ".join(x for x in (cand["vendor"], cand["product"]) if x) or pack_id,
        "source_name": pack_id.replace("-", "_"), "priority": 50,
        "fingerprint": cand["fingerprint"], "format": "regex",
        **({"header": cand["header"]} if cand["header"] else {}),
        "patterns": [cand["pattern"]], "map": field_map,
        "constants": {"class_uid": 4001, "class_name": "Network Activity", "category_uid": 4,
                      "metadata.product.vendor_name": cand["vendor"] or "Unknown",
                      "metadata.product.name": cand["product"] or "Unknown"},
    }
    header = ("# Generated by the LogSync synthesis loop (%s) and approved by an analyst.\n"
              % cand["generator"])
    return header + yaml.safe_dump(doc, sort_keys=False, allow_unicode=False, width=1000)


class SynthesisLoop:
    def __init__(self, settings: Settings, processor=None, llm=None, wasm=None):
        self.settings = settings
        self.processor = processor
        self.db = Database(settings.db_path)
        self.registry = processor.registry if processor else Registry(settings.data_dir / "packs",
                                                                      pack_signer(settings))
        self.llm = llm if llm is not None else OllamaClient(settings.ollama_url, settings.ollama_model)
        if wasm is None:
            from ..core.wasm_host import WasmEngine
            wasm = WasmEngine()
        self.wasm = wasm

    # ---------------------------------------------------------------- helpers
    def _dead_letters(self, fingerprint: str, limit: int = 500) -> list[tuple[str, bytes, str]]:
        rx = re.compile(fingerprint.encode())
        out = []
        for r in self.db.connect().execute(
                "SELECT event_id, source_host, doc FROM events WHERE status = 'unparsed' ORDER BY seq DESC LIMIT 20000"):
            raw = json.loads(r["doc"])["raw"]["text"].encode("utf-8")
            if rx.search(raw[:1024]):
                out.append((r["event_id"], raw, r["source_host"]))
                if len(out) >= limit:
                    break
        return out

    def _label(self, cand: infer.Candidate, sample: list[str]) -> tuple[infer.Candidate, str]:
        """Ask the model to name and map the drafted slots; everything it returns is checked."""
        full = cand.full_pattern
        captures = _CAPTURE.findall(full)
        slots = {"s%d" % i: (t, name) for i, (t, name) in enumerate(captures, 1)}
        template, i = full, 0

        def slot(mo):
            nonlocal i
            i += 1
            return "{s%d}" % i
        template = re.sub(r"\\(.)", r"\1", _CAPTURE.sub(slot, template))
        types = {k: t for k, (t, _) in slots.items()}
        try:
            if not self.llm.available():
                raise LLMUnavailable("model %s not available" % self.settings.ollama_model)
            out = self.llm.label(template, types, sample[:5])
        except (LLMUnavailable, ValueError) as e:
            log.info("LLM labelling skipped: %s", e)
            return cand, "drain (deterministic fallback - %s)" % ("model unavailable" if isinstance(e, LLMUnavailable)
                                                                  else "model output rejected")
        renames, used = {}, set(HEADER_FIELDS)
        suggestions = dict(cand.suggestions)
        for f in out["fields"]:
            if f["slot"] not in slots:
                continue
            gtype, old = slots[f["slot"]]
            if old in HEADER_FIELDS:
                continue
            new = _safe_name(f["name"])
            if new and new not in used and name_fits(new, gtype):
                renames[old] = new
                used.add(new)
            target = f["ues_field"] if f["ues_field"] in UES_TARGETS and compatible(f["ues_field"], gtype) else None
            key = renames.get(old, old)
            suggestions.pop(old, None)
            if target:
                suggestions[key] = target
        rename = lambda text: _CAPTURE.sub(lambda mo: "%%{%s:%s}" % (mo.group(1), renames.get(mo.group(2), mo.group(2))), text)
        cand.pattern = rename(cand.pattern)
        cand.suggestions = suggestions
        cand.vendor, cand.product = out["vendor"], out["product"]
        return cand, "%s (offline) labels + drain structure" % self.settings.ollama_model

    # ---------------------------------------------------------------- draft
    def draft(self, sample: list[str]) -> m.PackDraft:
        sample = [s.rstrip("\r\n") for s in sample if s.strip()][:50]
        # DETECT: the pasted lines identify the format; the dead-letter queue supplies
        # many more lines of it, so values that merely happen to repeat in a handful
        # of samples are not mistaken for fixed text.
        dl = self._dead_letters(infer.infer(sample).fingerprint)
        # learn from even-numbered dead letters, score on the odd ones (true held-out)
        learn = sample + [raw.decode("utf-8", "replace") for _, raw, _ in dl[0::2][:200]]
        cand = infer.infer(learn)
        cand, generator = self._label(cand, sample)
        cand.generator = generator
        dl = self._dead_letters(cand.fingerprint)
        held_out = [raw for _, raw, _ in dl[1::2]] or [raw for _, raw, _ in dl]
        c = {"header": cand.header or "", "pattern": cand.pattern, "fingerprint": cand.fingerprint,
             "vendor": cand.vendor, "product": cand.product, "generator": generator}
        mapping = {**{k: v for k, v in HEADER_FIELDS.items()}, **cand.suggestions}
        text = build_pack_text(c, mapping, "draft-candidate", "0.0.0")
        pack = load_pack(text)
        now = datetime.now(timezone.utc).isoformat()
        samples_b = [s.encode() for s in sample]
        checks = validate.validate(pack, c["header"] + c["pattern"], samples_b, held_out, self.wasm, now)
        rate = next(ck for ck in checks if ck["name"] == "match_rate")
        pool = held_out or samples_b
        matched = sum(1 for t in self.wasm.tokenize_many(pack.spec, pool) if t.ok and not t.unexplained)

        tok = PythonEngine().tokenize(pack.spec, samples_b[0])
        types = {name: t for t, name in _CAPTURE.findall(c["header"] + c["pattern"])}
        fields = [m.DraftField(name=f[0], grok=types.get(f[0], "?"),
                               sample_value=samples_b[0][f[1]:f[2]].decode("utf-8", "replace"),
                               bytes=(f[1], f[2]), mapped_to=mapping.get(f[0], "(ignore)"))
                  for f in tok.fields if f[0] in types]
        hosts = Counter(h for _, _, h in dl)
        literal = re.sub(r"\\(.)", r"\1", cand.fingerprint.split(r"\S+ ", 1)[-1].lstrip("^"))
        draft = m.PackDraft(
            draft_id="draft_" + uuid.uuid4().hex[:10],
            detected=m.DetectedFormat(fingerprint=literal, lines=len(dl),
                                      source_ip=hosts.most_common(1)[0][0] if hosts else "pasted sample"),
            generator=generator, sample=sample[:5], pattern=c["header"] + c["pattern"],
            confidence=round(matched / len(pool), 3), validation=[m.VerifyCheck(**ck) for ck in checks],
            fields=fields, ues_targets=UES_TARGETS + ["(ignore)"])
        self.db.connect().execute("INSERT INTO drafts (draft_id, created, doc) VALUES (?,?,?)",
                                  (draft.draft_id, time.time(),
                                   json.dumps({"draft": draft.model_dump(), "candidate": c})))
        log.info("draft %s: %s, confidence %.3f (%s)", draft.draft_id, generator, draft.confidence, rate["detail"])
        return draft

    # ---------------------------------------------------------------- approve
    def approve(self, req: m.ApproveRequest) -> m.ApproveResult:
        row = self.db.connect().execute("SELECT doc FROM drafts WHERE draft_id = ?", (req.draft_id,)).fetchone()
        if not row:
            from ..api.service import NotFound
            raise NotFound(req.draft_id)
        saved = json.loads(row["doc"])
        c, draft = saved["candidate"], saved["draft"]
        mapping = {f.name: f.mapped_to for f in req.fields}

        base = _slug("%s %s" % (c["vendor"], c["product"])) or \
            "generated-" + hashlib.sha256(c["fingerprint"].encode()).hexdigest()[:8]
        existing = [p for p in self.registry.active() if p.id == base]
        version = "0.1.0"
        if existing:
            major, minor, patch = (int(x) for x in existing[0].version.split("."))
            version = "%d.%d.%d" % (major, minor, patch + 1)
        text = build_pack_text(c, mapping, base, version)
        pack = load_pack(text)

        dl = self._dead_letters(c["fingerprint"], limit=100_000)
        samples = [s.encode() for s in draft["sample"]]
        checks = validate.validate(pack, c["header"] + c["pattern"], samples, [raw for _, raw, _ in dl][:500],
                                   self.wasm, datetime.now(timezone.utc).isoformat())
        if not validate.passed(checks):
            bad = next(ck for ck in checks if ck["status"] == "fail")
            raise ValueError("pack rejected by the gate: %s - %s" % (bad["name"], bad["detail"]))
        try:
            pack = self.registry.add(text)             # signs and hot-loads
        except PackError as e:
            raise ValueError(str(e)) from e
        signature = (self.registry.dir / ("%s.yaml.sig" % pack.ref)).read_text().strip()

        reparsed = 0
        if self.processor is not None:
            reparsed = self.processor.reprocess([eid for eid, _, _ in dl])
        status = "signed → hot-loaded → source live"
        if reparsed:
            status += " · %d archived events re-parsed" % reparsed
        mapped = sum(1 for t in mapping.values() if t not in ("", "(ignore)"))
        return m.ApproveResult(pack_id=pack.id, version=pack.version, draft_id=req.draft_id,
                               mapped_fields=mapped, signature=signature[:40] + "…", status=status)
